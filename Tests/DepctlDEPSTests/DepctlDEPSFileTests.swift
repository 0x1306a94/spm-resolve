import Testing
@testable import DepctlDEPS

@Test func renderUsesFieldOrderAndMarksComment() throws {
    let text = try DepctlDEPSText.render(
        repositories: [
            DepctlRepository(
                url: "https://github.com/hackiftekhar/IQTextView.git",
                commit: "text-sha",
                comment: "1.0.5 version"
            ),
            DepctlRepository(
                url: "https://github.com/hackiftekhar/IQKeyboardCore.git",
                commit: "core-sha",
                comment: "1.0.9 version"
            ),
        ],
        directoryPrefix: "third_party/Packages/"
    )

    #expect(text == """
    [
      {
        "url": "https://github.com/hackiftekhar/IQKeyboardCore.git",
        "commit": "core-sha",
        "dir": "third_party/Packages/IQKeyboardCore",
        "comment": "1.0.9 version Generated by spm-resolve"
      },
      {
        "url": "https://github.com/hackiftekhar/IQTextView.git",
        "commit": "text-sha",
        "dir": "third_party/Packages/IQTextView",
        "comment": "1.0.5 version Generated by spm-resolve"
      }
    ]

    """)
}

@Test func renderEscapesComment() throws {
    let text = try DepctlDEPSText.render(
        repositories: [
            DepctlRepository(url: "https://example.com/a.git", commit: "abc", comment: "say \"hi\""),
        ],
        directoryPrefix: "third_party/Packages"
    )
    #expect(text.contains(#""comment": "say \"hi\" Generated by spm-resolve""#))
}

@Test func emptyRepositoriesRenderAnEmptyArray() throws {
    let text = try DepctlDEPSText.render(repositories: [], directoryPrefix: "third_party/Packages")
    #expect(text == "[]\n")
}

@Test func remoteRootManifestUsesExactVersionOrRevision() throws {
    let versioned = try remoteRootManifest(
        url: "https://github.com/hackiftekhar/IQKeyboardManager.git",
        exactVersion: "8.0.3",
        revision: nil
    )
    #expect(versioned.contains(#".package(url: "https://github.com/hackiftekhar/IQKeyboardManager.git", exact: "8.0.3")"#))
    let pinned = try remoteRootManifest(url: "git@github.com:hackiftekhar/IQKeyboardManager.git", exactVersion: nil, revision: "abc123")
    #expect(pinned.contains(#"revision: "abc123""#))
    #expect(isRemotePackageURL("https://github.com/hackiftekhar/IQKeyboardManager.git"))
    #expect(isRemotePackageURL("git@github.com:hackiftekhar/IQKeyboardManager.git"))
    #expect(!isRemotePackageURL("Packages/App"))
    #expect(throws: DepctlDEPSError.self) {
        try remoteRootManifest(url: "https://example.com/a.git", exactVersion: "1.0.0", revision: "abc")
    }
}
