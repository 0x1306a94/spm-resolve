public struct DepctlRepository: Equatable, Sendable {
    public var url: String
    public var commit: String
    public var comment: String

    public init(url: String, commit: String, comment: String) {
        self.url = url
        self.commit = commit
        self.comment = comment
    }
}

public struct DepctlDEPSError: Error, Equatable, CustomStringConvertible {
    public var message: String

    public init(_ message: String) {
        self.message = message
    }

    public var description: String {
        message
    }
}

public enum DepctlDEPSText {
    public static let marker = "Generated by spm-resolve"

    public static func render(repositories: [DepctlRepository], directoryPrefix: String) throws -> String {
        if directoryPrefix.isEmpty || directoryPrefix.allSatisfy({ $0 == "/" }) {
            throw DepctlDEPSError("directory prefix is empty")
        }
        if repositories.isEmpty {
            return "[]\n"
        }

        var seenLocations: Set<String> = []
        var seenDirectories: Set<String> = []
        var lines: [String] = []
        for repository in repositories.sorted(by: { $0.url < $1.url }) {
            if repository.commit.isEmpty {
                throw DepctlDEPSError("missing commit for \(repository.url)")
            }
            let location = normalizeLocation(repository.url)
            if !seenLocations.insert(location).inserted {
                throw DepctlDEPSError("duplicate dependency \(repository.url)")
            }
            let directory = try repositoryDirectory(prefix: directoryPrefix, url: repository.url)
            if !seenDirectories.insert(normalizeDirectory(directory)).inserted {
                throw DepctlDEPSError("duplicate directory \(directory)")
            }
            let comment = repository.comment.isEmpty ? marker : "\(repository.comment) \(marker)"
            lines.append("""
              {
                "url": "\(escape(repository.url))",
                "commit": "\(escape(repository.commit))",
                "dir": "\(escape(directory))",
                "comment": "\(escape(comment))"
              }
            """)
        }
        return "[\n" + lines.joined(separator: ",\n") + "\n]\n"
    }
}

private func repositoryDirectory(prefix: String, url: String) throws -> String {
    let name = repositoryName(from: url)
    if name.isEmpty {
        throw DepctlDEPSError("cannot derive a directory name from \(url)")
    }
    var prefix = trimEdges(prefix)
    while prefix.hasSuffix("/") {
        prefix.removeLast()
    }
    return "\(prefix)/\(name)"
}

public func isRemotePackageURL(_ value: String) -> Bool {
    value.contains("://") || value.hasPrefix("git@")
}

public func remoteRootManifest(url: String, exactVersion: String?, revision: String?) throws -> String {
    let requirement: String
    switch (exactVersion, revision) {
    case let (version?, nil) where !version.isEmpty:
        requirement = "exact: \"\(escape(version))\""
    case let (nil, revision?) where !revision.isEmpty:
        requirement = "revision: \"\(escape(revision))\""
    case (nil, nil):
        throw DepctlDEPSError("remote package requires --version or --revision")
    case (_, nil), (nil, _):
        throw DepctlDEPSError("remote package version or revision is empty")
    default:
        throw DepctlDEPSError("pass only one of --version or --revision")
    }
    return """
    // swift-tools-version: 6.4
    import PackageDescription
    let package = Package(
        name: "spm-resolve-root",
        dependencies: [
            .package(url: "\(escape(url))", \(requirement)),
        ]
    )

    """
}

public func repositoryName(from url: String) -> String {
    var text = trimEdges(url)
    while text.hasSuffix("/") {
        text.removeLast()
    }
    if text.lowercased().hasSuffix(".git") {
        text.removeLast(4)
    }
    if let slash = text.lastIndex(of: "/") {
        return String(text[text.index(after: slash)...])
    }
    if let colon = text.lastIndex(of: ":") {
        return String(text[text.index(after: colon)...])
    }
    return text
}

private func normalizeLocation(_ value: String) -> String {
    var text = trimEdges(value)
    while text.hasSuffix("/") {
        text.removeLast()
    }
    if text.lowercased().hasSuffix(".git") {
        text.removeLast(4)
    }
    return text.lowercased()
}

private func normalizeDirectory(_ value: String) -> String {
    var text = value
    while text.hasSuffix("/") {
        text.removeLast()
    }
    return text
}

private func trimEdges(_ value: String) -> String {
    var text = value
    while let first = text.first, first.isWhitespace || first.isNewline {
        text.removeFirst()
    }
    while let last = text.last, last.isWhitespace || last.isNewline {
        text.removeLast()
    }
    return text
}

private func escape(_ value: String) -> String {
    var result = ""
    for character in value {
        switch character {
        case "\\":
            result += "\\\\"
        case "\"":
            result += "\\\""
        case "\n":
            result += "\\n"
        case "\r":
            result += "\\r"
        case "\t":
            result += "\\t"
        default:
            result.append(character)
        }
    }
    return result
}
